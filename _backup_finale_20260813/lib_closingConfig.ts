export interface QALayout {
  kind: QALayoutKind;
  leftTitle?: string;
  rightTitle?: string;
  rows?: { left: string; right: string }[]; // compare
  segments?: { time: string; items: string[] }[]; // timeline
  items?: string[]; // list
  steps?: string[]; // steps（带序号）
  grid?: string[]; // grid（卡片）
  bottom?: string; // 底部收口一句话
  needConfig?: boolean; // 依赖真实规则，大屏标注「规则待确认」，避免模糊承诺
}

